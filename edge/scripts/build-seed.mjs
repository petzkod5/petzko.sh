#!/usr/bin/env node
// Generates edge/migrations/0004_seed_content.sql from the static content files
// in frontend/src/content/. Run once before the first remote migration:
//   node edge/scripts/build-seed.mjs
//
// Uses INSERT OR IGNORE so the seed is applied exactly once — admin edits in D1
// are never clobbered by re-running migrations.

import { readFileSync, writeFileSync } from 'fs'
import { fileURLToPath } from 'url'
import { join, dirname } from 'path'

// Resolve paths relative to the repo root (two levels up from edge/scripts/).
const here = dirname(fileURLToPath(import.meta.url))
const root = join(here, '..', '..')
const contentDir = join(root, 'frontend', 'src', 'content')

// yaml is a frontend dep — import from the adjacent node_modules.
const { parse } = await import(
  join(root, 'frontend', 'node_modules', 'yaml', 'dist', 'index.js')
)

// ── Minimal frontmatter parser (mirrors frontend/src/content/frontmatter.ts) ──

function parseFrontmatter(raw) {
  const match = raw.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n?/)
  if (!match) return { data: {}, content: raw }
  const data = {}
  for (const line of match[1].split(/\r?\n/)) {
    const idx = line.indexOf(':')
    if (idx === -1) continue
    const key = line.slice(0, idx).trim()
    const value = line
      .slice(idx + 1)
      .trim()
      .replace(/^["']|["']$/g, '')
    if (key) data[key] = value
  }
  return { data, content: raw.slice(match[0].length) }
}

// ── Read + normalise content ───────────────────────────────────────────────────

const aboutRaw = readFileSync(join(contentDir, 'about.md'), 'utf8')
const fm = parseFrontmatter(aboutRaw)
const about = {
  heading: fm.data.title ?? 'About',
  avatar: fm.data.avatar ?? '',
  avatarAlt: fm.data.avatarAlt ?? '',
  body: fm.content.replace(/^\s+/, ''),
}

const contactsRaw = readFileSync(join(contentDir, 'contacts.yaml'), 'utf8')
const contacts = ((parse(contactsRaw).contacts ?? [])).map((c) => ({
  type: String(c.type ?? ''),
  url: String(c.url ?? ''),
  description: String(c.description ?? '').trim(),
  click: Boolean(c.click),
  newTab: Boolean(c.newTab),
  copy: Boolean(c.copy),
}))

const portfolioRaw = readFileSync(join(contentDir, 'portfolio.yaml'), 'utf8')
const portfolio = ((parse(portfolioRaw).portfolio ?? [])).map((p) => ({
  type: String(p.type ?? ''),
  name: String(p.name ?? ''),
  url: String(p.url ?? ''),
  icon: String(p.icon ?? '').trim(),
  company: String(p.company ?? ''),
  description: String(p.description ?? '').trim(),
}))

// ── Emit SQL ──────────────────────────────────────────────────────────────────

function toSqlValue(obj) {
  // JSON.stringify produces double-quoted strings; we embed it in a SQL
  // single-quoted literal so any single quotes inside must be doubled.
  return JSON.stringify(obj).replace(/'/g, "''")
}

const sections = [
  ['about', about],
  ['contacts', contacts],
  ['portfolio', portfolio],
]

const lines = [
  '-- Auto-generated by edge/scripts/build-seed.mjs — do not hand-edit.',
  '-- INSERT OR IGNORE ensures this only seeds once; admin edits in D1 are preserved.',
]

for (const [key, value] of sections) {
  lines.push(
    `INSERT OR IGNORE INTO content (key, value, updated_at)`,
    `VALUES ('${key}', '${toSqlValue(value)}', CAST(strftime('%s','now') AS INTEGER) * 1000);`,
    '',
  )
}

const out = join(here, '..', 'migrations', '0004_seed_content.sql')
writeFileSync(out, lines.join('\n') + '\n')
console.log(`wrote ${out}`)
